for path in sorted(LOCALES.glob("*.json")):
    locale = path.stem
    catalog = json.loads(path.read_text(encoding="utf-8"))
    fresh = {}
    for key, translations in K.items():
        if key not in catalog:
            fresh[key] = translations.get(locale, translations["en"])
    if not fresh:
        continue
    if locale == "tr":
        raw = subprocess.run(
            ["git", "show", f"origin/main:{path.as_posix()}"], capture_output=True
        ).stdout.decode("utf-8")
        block = ",\r\n".join(
            f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}"
            for k, v in fresh.items()
        )
        body = raw.rstrip()
        inner = body[:-1].rstrip()
        path.write_bytes((inner + ",\r\n" + block + "\r\n}\r\n").encode("utf-8"))
    else:
        catalog.update(fresh)
        path.write_text(
            json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
    print(f"updated {locale}")
print("done")
